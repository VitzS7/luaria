    #[test]
    fn getgc_so_chama_os_slots_e_salta_por_dentro() {
        let bloco = montar_bloco(0x1000_0000);
        let codigo = &bloco[REL_GETGC..];
        let fim = OFF_GETGC + codigo.len() as u64;
        let mut decodificador = Decoder::with_ip(64, codigo, OFF_GETGC, DecoderOptions::NONE);
        let mut chamadas = Vec::new();
        let mut rets = 0;
        while decodificador.can_decode() {
            let instrucao = decodificador.decode();
            assert!(!instrucao.is_invalid(), "instrução inválida em {:#x}", instrucao.ip());
            if instrucao.mnemonic() == Mnemonic::Call {
                assert!(instrucao.is_ip_rel_memory_operand(), "call fora de slot em {:#x}", instrucao.ip());
                chamadas.push(instrucao.ip_rel_memory_address());
            }
            if instrucao.mnemonic() == Mnemonic::Lea {
                let destino = instrucao.ip_rel_memory_address();
                assert!((OFF_GETGC..fim).contains(&destino), "lea para fora em {:#x}", instrucao.ip());
            }
            if instrucao.flow_control() == FlowControl::Return {
                rets += 1;
            }
            if matches!(instrucao.flow_control(), FlowControl::ConditionalBranch | FlowControl::UnconditionalBranch) {
                let destino = instrucao.near_branch_target();
                assert!((OFF_GETGC..fim).contains(&destino), "salto para fora em {:#x}", instrucao.ip());
            }
        }
        assert_eq!(rets, 2);
        let slots = [OFF_NATIVAS + REL_SLOT_CREATETABLE as u64, OFF_NATIVAS + REL_SLOT_VISITGCO as u64];
        assert_eq!(chamadas.len(), 3);
        for destino in chamadas {
            assert!(slots.contains(&destino), "call to {destino:#x} outside the slots");
        }
    }

