//! Funções nativas x86-64 gravadas na página do stub (ao lado de `hook.rs`).
//!
//! Por que à mão e com slots: as funções do jogo não são chamadas por nome. O
//! bloco guarda um ponteiro por função (chamada indireta por slot) e o motor preenche
//! esses slots com `base + VA` depois que o `libroblox.so` está carregado. Assim o
//! código não muda entre execuções, só os quatro endereços.


/// Início do bloco dentro da página do stub. Faixa livre: 0x360..0x700 (OFF_FLAG).
pub const OFF_NATIVAS: u64 = 0x380;

/// Deslocamento da `getconstant` dentro do bloco: alinhado depois dos slots (0xb8..0xd8).
const REL_GETCONSTANT: usize = 0xe0;
/// Logo depois da `getconstant` (que termina em 0x168).
const REL_GETUPVALUE: usize = 0x168;
/// Slots de `lua_createtable` e `luaM_visitgco`: ficam antes da getgc para o `call` ter disp fixo.
const REL_SLOT_CREATETABLE: usize = 0x200;
const REL_SLOT_VISITGCO: usize = 0x208;
/// Logo depois dos slots (getupvalue termina em 0x1fc). Código da getgc e do visitor.
const REL_GETGC: usize = 0x210;
pub const TAM_BLOCO: usize = REL_GETGC + CODIGO_GETGC.len();

/// Quantas closures C o motor empilha como args do chunk (grm, srm, sro, getconstant, getupvalue, getgc, pe, pr, setconstant, setupvalue).
pub const QTD: u64 = 10;

/// `LUARIA_NATIVAS=0` desliga (kill-switch pra bisseção ao vivo); qualquer outro valor deixa ligado.
pub fn ligadas() -> bool {
    ligadas_de(std::env::var("LUARIA_NATIVAS").ok().as_deref())
}

fn ligadas_de(v: Option<&str>) -> bool {
    v.map_or(true, |x| x.trim() != "0")
}

