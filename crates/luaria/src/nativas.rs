/// Monta o bloco pronto para gravar em `OFF_NATIVAS`, com os slots apontando
/// para as funções do jogo no módulo carregado em `base_modulo`.
pub fn montar_bloco(base_modulo: u64) -> [u8; TAM_BLOCO] {
    let mut bloco = [0u8; TAM_BLOCO];
    bloco[..CODIGO.len()].copy_from_slice(&CODIGO);
    bloco[REL_GETCONSTANT..REL_GETCONSTANT + CODIGO_GETCONSTANT.len()].copy_from_slice(&CODIGO_GETCONSTANT);
    bloco[REL_GETUPVALUE..REL_GETUPVALUE + CODIGO_GETUPVALUE.len()].copy_from_slice(&CODIGO_GETUPVALUE);
    bloco[REL_GETGC..].copy_from_slice(&CODIGO_GETGC);
    for funcao in FUNCOES_JOGO {
        let endereco = base_modulo.wrapping_add(funcao.va);
        bloco[funcao.slot..funcao.slot + 8].copy_from_slice(&endereco.to_le_bytes());
    }
    bloco
}

pub fn prologo_esperado() -> Vec<(u64, [u8; 32])> {
    let mut lista: Vec<(u64, [u8; 32])> = FUNCOES_JOGO.iter().map(|f| (f.va, f.prologo)).collect();
    lista.push((PUSHLSTRING_VA, PROLOGO_PUSHLSTRING));
    lista.push((BARRIERF_VA, PROLOGO_BARRIERF));
    lista.push((LUA_SETUPVALUE_VA, PROLOGO_LUA_SETUPVALUE));
    lista
}

/// `lerpeda(va)` devolve os bytes do `.so` nesse VA. Falha se algum prólogo
/// não bate, ou seja, se o payload mudou desde que as constantes foram medidas.
pub fn conferir_prologos<'a>(lerpeda: impl Fn(u64) -> Option<&'a [u8]>) -> Result<(), String> {
    for (va, esperado) in prologo_esperado() {
        let lido = lerpeda(va).and_then(|b| b.get(..32));
        if lido != Some(&esperado[..]) {
            return Err(format!("prologue at {va:#x} differs from the current payload"));
        }
    }
    Ok(())
}

