    #[test]
    fn desmontagem_bate_com_as_chamadas_aos_slots() {
        let bloco = montar_bloco(0x1000_0000);
        // Só o código: os slots são dados e não devem ser desmontados.
        let codigo = &bloco[..FUNCOES_JOGO[0].slot];
        let mut decodificador = Decoder::with_ip(64, codigo, OFF_NATIVAS, DecoderOptions::NONE);
        let mut chamadas = Vec::new();
        let mut rets = 0;
        while decodificador.can_decode() {
            let instrucao = decodificador.decode();
            assert!(!instrucao.is_invalid(), "instrução inválida em {:#x}", instrucao.ip());
            if instrucao.mnemonic() == Mnemonic::Call && instrucao.is_ip_rel_memory_operand() {
                chamadas.push(instrucao.ip_rel_memory_address());
            }
            if instrucao.flow_control() == FlowControl::Return {
                rets += 1;
            }
        }
        assert_eq!(rets, 4);
        // Só os slots do bloco são chamados; qualquer outro destino é bug de offset.
        for destino in chamadas {
            assert!(
                FUNCOES_JOGO.iter().any(|f| OFF_NATIVAS + f.slot as u64 == destino),
                "call to {destino:#x} outside the slots"
            );
        }
    }

    /// Confere que a rotina só lê memória: sem `call`, saltos presos no próprio código.
    /// Devolve quantos `ret` ela tem.
    fn conferir_so_le_memoria(inicio: u64, codigo: &[u8]) -> usize {
        let fim = inicio + codigo.len() as u64;
        let mut decodificador = Decoder::with_ip(64, codigo, inicio, DecoderOptions::NONE);
        let mut rets = 0;
        while decodificador.can_decode() {
            let instrucao = decodificador.decode();
            assert!(!instrucao.is_invalid(), "instrução inválida em {:#x}", instrucao.ip());
            assert_ne!(instrucao.mnemonic(), Mnemonic::Call, "rotina não chama função do jogo");
            if instrucao.flow_control() == FlowControl::Return {
                rets += 1;
            }
            if matches!(instrucao.flow_control(), FlowControl::ConditionalBranch | FlowControl::UnconditionalBranch) {
                let destino = instrucao.near_branch_target();
                assert!((inicio..fim).contains(&destino), "salto para fora em {:#x}", instrucao.ip());
            }
        }
        rets
    }

