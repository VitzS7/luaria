//! Nativas do canal host→jogo: `__n_pe` envia um pedido e `__n_pr` recebe a resposta.
//!
//! Por que página própria e não o bloco de `nativas.rs`: o bloco do stub já ocupa
//! quase toda a faixa livre. A página é RWX: o código fica nela e o host grava
//! o endereço de `lua_pushlstring` (slot) e o ponteiro do anel (`ponte_layout`).
//!
//! Por que `lock cmpxchg` no `dono`: duas threads do jogo podem escolher o mesmo
//! slot. Quem perde tenta o próximo em vez de esperar, porque o `pe` roda dentro
//! de `luaD_call` e não pode bloquear. O `pr` espera, porque o slot é dele.
//!
//! Código gerado a partir de um `.s` que não fica no repo. Mudar o assembly exige remontar e recopiar `CODIGO`; os testes
//! conferem saltos, chamadas e comportamento contra um anel simulado.

pub const TAM_PAGINA: usize = 0x1000;
/// Início de cada função dentro da página.
pub const OFF_PE: usize = 0x000;
pub const OFF_PR: usize = 0x300;
pub const OFF_CHECA_ANEL: usize = 0x600;
/// Slot com o endereço de `lua_pushlstring`, chamado indiretamente por ele.
pub const OFF_SLOT_PUSHLSTRING: usize = 0xff0;
/// Ponteiro do anel no processo do jogo, gravado pelo host.
pub const OFF_PTR_ANEL: usize = 0xff8;
/// `n_sk` (setconstant) e `n_su` (setupvalue): ficam depois de `checa_anel`. Cada um
/// começa no próprio offset porque o `.s` usa `.org` fixo.
pub const OFF_SK: usize = 0x700;
pub const OFF_SU: usize = 0x800;
/// Slots da barreira GC e do `lua_setupvalue` do jogo, chamados por `call [rip+slot]`.
pub const OFF_SLOT_BARRIERF: usize = 0xfd8;
pub const OFF_SLOT_LUA_SETUPVALUE: usize = 0xfe0;

/// Tag de string no TValue (no build medido: `luaS_newlstr` grava 6 em `ts+2`). 5 é vector.
pub const TT_STRING: u32 = 6;

/// Página pronta para o mmap RWX. `ptr_anel` fica 0 até o host mapear o anel.
pub fn montar_pagina(pushlstring: u64, barrierf: u64, setupvalue: u64, ptr_anel: u64) -> [u8; TAM_PAGINA] {
    let mut pagina = [0u8; TAM_PAGINA];
    pagina[..CODIGO.len()].copy_from_slice(&CODIGO);
    pagina[OFF_SK..OFF_SK + CODIGO_SK_SU.len()].copy_from_slice(&CODIGO_SK_SU);
    pagina[OFF_SLOT_PUSHLSTRING..OFF_SLOT_PUSHLSTRING + 8].copy_from_slice(&pushlstring.to_le_bytes());
    pagina[OFF_SLOT_BARRIERF..OFF_SLOT_BARRIERF + 8].copy_from_slice(&barrierf.to_le_bytes());
    pagina[OFF_SLOT_LUA_SETUPVALUE..OFF_SLOT_LUA_SETUPVALUE + 8].copy_from_slice(&setupvalue.to_le_bytes());
    pagina[OFF_PTR_ANEL..OFF_PTR_ANEL + 8].copy_from_slice(&ptr_anel.to_le_bytes());
    pagina
}

