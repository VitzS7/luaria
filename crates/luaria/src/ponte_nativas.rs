    fn decodificar(inicio: usize, fim: usize) -> Vec<Instruction> {
        decodificar_de(&CODIGO[inicio..fim], inicio)
    }

    fn decodificar_de(bytes: &[u8], inicio: usize) -> Vec<Instruction> {
        let mut dec = Decoder::with_ip(64, bytes, inicio as u64, DecoderOptions::NONE);
        let mut instrucoes = Vec::new();
        while dec.can_decode() {
            let instrucao = dec.decode();
            assert!(!instrucao.is_invalid(), "instrução inválida em {:#x}", instrucao.ip());
            instrucoes.push(instrucao);
        }
        instrucoes
    }

