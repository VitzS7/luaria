        assert_eq!(amb.ler(0, anel::SLOT_LEN_REQ), 3);
        assert_eq!(amb.ler(0, anel::SLOT_TIPO), 1);
        assert_eq!(amb.ler(0, anel::SLOT_FLAGS), 0);
