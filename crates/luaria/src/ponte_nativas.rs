    extern "C" {
        fn mmap(end: *mut c_void, len: usize, prot: i32, flags: i32, fd: i32, off: i64) -> *mut c_void;
        fn munmap(end: *mut c_void, len: usize) -> i32;
    }
    const PROT_RW: i32 = 3;
    const PROT_RWX: i32 = 7;
    const MAP_PRIVADO_ANON: i32 = 0x22;
    const MAP_FALHOU: *mut c_void = usize::MAX as *mut c_void;

    thread_local! {
        static CORPOS: RefCell<Vec<Vec<u8>>> = RefCell::new(Vec::new());
        /// (L, owner, valor) de cada barreira falsa.
        static BARREIRAS: RefCell<Vec<(u64, u64, u64)>> = RefCell::new(Vec::new());
        /// (L, funcindex, n, top na chamada) de cada `lua_setupvalue` falso.
        static SETUPVALUES: RefCell<Vec<(u64, i32, i32, u64)>> = RefCell::new(Vec::new());
        static SETUP_ACHA: Cell<bool> = Cell::new(true);
    }

    unsafe extern "C" fn barreira_falsa(l: *mut u64, owner: *mut u8, valor: *mut u8) {
        BARREIRAS.with(|b| b.borrow_mut().push((l as u64, owner as u64, valor as u64)));
    }

    /// Como o real: tira o topo no sucesso e devolve o nome (aqui qualquer string).
    unsafe extern "C" fn setupvalue_falso(l: *mut u64, funcindex: i32, n: i32) -> *const u8 {
        let top = *l.add(5);
        SETUPVALUES.with(|s| s.borrow_mut().push((l as u64, funcindex, n, top)));
        if !SETUP_ACHA.with(|c| c.get()) {
            return std::ptr::null();
        }
        *l.add(5) = top - 16;
        b"up\0".as_ptr()
    }

    /// Closure e Proto falsos: isC em cl+6, Proto em cl+0x18, k em proto+0x30, sizek em +0x8c.
    /// Os Vecs ficam vivos junto com a struct, então os ponteiros não mudam.
    struct Funcao {
        cl: Vec<u8>,
        proto: Vec<u8>,
        k: Vec<u8>,
    }

    impl Funcao {
        fn nova(constantes: &[(u32, u64)]) -> Self {
            let mut k = vec![0u8; 16 * constantes.len().max(1)];
            for (i, (tt, valor)) in constantes.iter().enumerate() {
                k[16 * i..16 * i + 8].copy_from_slice(&valor.to_le_bytes());
                k[16 * i + 0xc..16 * i + 0x10].copy_from_slice(&tt.to_le_bytes());
            }
            let mut proto = vec![0u8; 0x100];
            proto[0x30..0x38].copy_from_slice(&(k.as_ptr() as u64).to_le_bytes());
            proto[0x8c..0x90].copy_from_slice(&(constantes.len() as u32).to_le_bytes());
            let mut cl = vec![0u8; 0x40];
            cl[0x18..0x20].copy_from_slice(&(proto.as_ptr() as u64).to_le_bytes());
            Self { cl, proto, k }
        }

        fn valor(&self) -> u64 {
            self.cl.as_ptr() as u64
        }

        fn constante(&self, i: usize) -> (u32, u64) {
            let tt = u32::from_le_bytes(self.k[16 * i + 0xc..16 * i + 0x10].try_into().unwrap());
            let valor = u64::from_le_bytes(self.k[16 * i..16 * i + 8].try_into().unwrap());
            (tt, valor)
        }
    }

    /// TString falso: len em +0x14 e dados em +0x18, como o `ler_tstring`.
    fn tstring(bytes: &[u8]) -> Vec<u8> {
        let mut t = vec![0u8; 0x18 + bytes.len()];
        t[0x14..0x18].copy_from_slice(&(bytes.len() as u32).to_le_bytes());
        t[0x18..].copy_from_slice(bytes);
        t
    }

    /// Stand-in do `lua_pushlstring`: guarda a cópia e empilha um TString falso.
    unsafe extern "C" fn pushlstring_falso(l: *mut u64, s: *const u8, len: usize) {
        let ptr = CORPOS.with(|c| {
            let mut c = c.borrow_mut();
            c.push(tstring(unsafe { std::slice::from_raw_parts(s, len) }));
            c.last().unwrap().as_ptr() as u64
        });
        unsafe {
            let topo = *l.add(5) as *mut u8;
            *(topo as *mut u64) = ptr;
            *(topo.add(0xc) as *mut u32) = TT_STRING;
            *l.add(5) = topo as u64 + 16;
        }
    }

    struct Ambiente {
        pagina: *mut u8,
        anel: *mut u8,
        /// Índices: 1 = stack_last (+0x08), 4 = base (+0x20), 5 = top (+0x28).
        lstate: Vec<u64>,
        pilha: Vec<u64>,
    }

    impl Ambiente {
        fn novo() -> Self {
            unsafe {
                let pagina = mmap(std::ptr::null_mut(), TAM_PAGINA, PROT_RWX, MAP_PRIVADO_ANON, -1, 0);
                let anel_mem = mmap(std::ptr::null_mut(), anel::TAM_ANEL, PROT_RW, MAP_PRIVADO_ANON, -1, 0);
                assert!(pagina != MAP_FALHOU && anel_mem != MAP_FALHOU, "mmap falhou");
                let pagina = pagina as *mut u8;
                let anel_mem = anel_mem as *mut u8;
                std::ptr::copy_nonoverlapping(anel::MAGIC.as_ptr(), anel_mem, 8);
                (anel_mem.add(anel::OFF_VERSAO) as *mut u32).write_unaligned(anel::VERSAO);
                BARREIRAS.with(|b| b.borrow_mut().clear());
                SETUPVALUES.with(|s| s.borrow_mut().clear());
                SETUP_ACHA.with(|c| c.set(true));
                let bytes = montar_pagina(
                    pushlstring_falso as *const () as usize as u64,
                    barreira_falsa as *const () as usize as u64,
                    setupvalue_falso as *const () as usize as u64,
                    anel_mem as u64,
                );
                std::ptr::copy_nonoverlapping(bytes.as_ptr(), pagina, TAM_PAGINA);
                Self { pagina, anel: anel_mem, lstate: vec![0; 8], pilha: vec![0; 128] }
            }
        }

        /// Roda a nativa com `args` como (tt, valor) e devolve o retorno e os valores (tt, valor).
        fn chamar(&mut self, offset: usize, args: &[(u32, u64)]) -> (i32, Vec<(u32, u64)>) {
            unsafe {
                for (i, (tt, valor)) in args.iter().enumerate() {
                    self.pilha[2 * i] = *valor;
                    self.pilha[2 * i + 1] = (*tt as u64) << 32;
                }
                let base = self.pilha.as_mut_ptr() as u64;
                self.lstate[1] = base + 128 * 8;
                self.lstate[4] = base;
                self.lstate[5] = base + 16 * args.len() as u64;
                let nativa: unsafe extern "C" fn(*mut u64) -> i32 = std::mem::transmute(self.pagina.add(offset));
                let n = nativa(self.lstate.as_mut_ptr());
                let topo = self.lstate[5];
                let valores = (0..n.max(0) as u64)
                    .map(|k| {
                        let p = (topo - 16 * (n as u64 - k)) as *const u8;
                        ((p.add(0xc) as *const u32).read_unaligned(), (p as *const u64).read_unaligned())
                    })
                    .collect();
                (n, valores)
            }
        }

        fn ler(&self, slot: usize, campo: usize) -> u32 {
            unsafe { (self.anel.add(anel::off_cab_slot(slot) + campo) as *const u32).read_unaligned() }
        }

        fn gravar(&self, slot: usize, campo: usize, valor: u32) {
            unsafe { (self.anel.add(anel::off_cab_slot(slot) + campo) as *mut u32).write_unaligned(valor) }
        }

        fn bytes_anel(&self, deslocamento: usize, len: usize) -> &[u8] {
            unsafe { std::slice::from_raw_parts(self.anel.add(deslocamento), len) }
        }

        fn gravar_anel_u32(&self, deslocamento: usize, valor: u32) {
            unsafe { (self.anel.add(deslocamento) as *mut u32).write_unaligned(valor) }
        }

        fn zerar_magic(&self) {
            unsafe { std::ptr::write_bytes(self.anel, 0, 8) }
        }
    }

    impl Drop for Ambiente {
        fn drop(&mut self) {
            unsafe {
                munmap(self.pagina as *mut c_void, TAM_PAGINA);
                munmap(self.anel as *mut c_void, anel::TAM_ANEL);
            }
        }
    }

